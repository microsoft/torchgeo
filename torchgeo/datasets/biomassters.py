"""BioMassters Dataset."""

import os
from collections.abc import Sequence
from typing import ClassVar, Literal

import einops
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import rasterio
import torch
from matplotlib.figure import Figure
from torch import Tensor

from .errors import DatasetNotFoundError
from .geo import NonGeoDataset
from .utils import Path, Sample, quantile_normalization


class BioMassters(NonGeoDataset):
    """BioMassters Dataset for Aboveground Biomass prediction.

    Dataset intended for Aboveground Biomass (AGB) prediction
    over Finnish forests based on Sentinel 1 and 2 data with
    corresponding target AGB mask values generated by Light Detection
    and Ranging (LiDAR).

    Dataset Format:

    * .tif files for Sentinel 1 and 2 data
    * .tif file for pixel wise AGB target mask
    * .csv files for metadata regarding features and targets

    Dataset Features:

    * 13,000 target AGB masks of size (256x256px)
    * 12 months of data per target mask
    * Sentinel 1 and Sentinel 2 data for each location
    * Sentinel 1 available for every month
    * Sentinel 2 available for almost every month
      (not available for every month due to ESA acquisition halt over the region
      during particular periods)

    If you use this dataset in your research, please cite the following paper:

    * https://nascetti-a.github.io/BioMasster/

    .. note::
        This dataset can be downloaded from `Torchgeo Hugging Face Hub <https://huggingface.co/datasets/torchgeo/biomassters>`_.

    .. versionadded:: 0.5
    """

    valid_splits = ('train', 'test')
    valid_sensors = ('S1', 'S2')
    channel_counts: ClassVar[dict[str, int]] = {'S1': 4, 'S2': 11}

    metadata_filename = 'biomassters_features_metadata.csv'

    def __init__(
        self,
        root: Path = 'data',
        split: Literal['train', 'test'] = 'train',
        sensors: Sequence[Literal['S1', 'S2']] = ('S1', 'S2'),
        as_time_series: bool = False,
    ) -> None:
        """Initialize a new instance of BioMassters dataset.

        If ``as_time_series=False`` (the default), each time step becomes its own
        sample with the target being shared across multiple samples.

        Args:
            root: root directory where dataset can be found
            split: train or test split
            sensors: which sensors to consider for the sample, Sentinel 1 and/or
                Sentinel 2 ('S1', 'S2')
            as_time_series: whether or not to return all available
                time-steps or just a single one for a given target location

        Raises:
            AssertionError: if ``split`` or ``sensors`` is invalid
            DatasetNotFoundError: If dataset is not found.
        """
        self.root = root

        assert split in self.valid_splits, (
            f'Please choose one of the valid splits: {self.valid_splits}.'
        )
        self.split = split

        assert set(sensors).issubset(set(self.valid_sensors)), (
            f'Please choose a subset of valid sensors: {self.valid_sensors}.'
        )
        self.sensors = tuple(sensors)
        self.as_time_series = as_time_series

        self._verify()

        # open metadata csv files
        self.df = pd.read_csv(os.path.join(self.root, self.metadata_filename))

        # filter sensors
        self.df = self.df[self.df['satellite'].isin(self.sensors)]

        # filter split
        self.df = self.df[self.df['split'] == self.split]

        # generate numerical month from filename since first month is September
        # and has numerical index of 0
        self.df['num_month'] = (
            self.df['filename']
            .str.split('_', expand=True)[2]
            .str.split('.', expand=True)[0]
            .astype(int)
        )

        # set dataframe index depending on the task for easier indexing
        if self.as_time_series:
            self.df['num_index'] = self.df.groupby(['chip_id']).ngroup()
        else:
            filter_df = (
                self.df.groupby(['chip_id', 'month'])['satellite'].count().reset_index()
            )
            filter_df = filter_df[filter_df['satellite'] == len(self.sensors)].drop(
                'satellite', axis=1
            )
            # guarantee that each sample has corresponding number of images available
            self.df = self.df.merge(filter_df, on=['chip_id', 'month'], how='inner')

            self.df['num_index'] = self.df.groupby(['chip_id', 'month']).ngroup()

    def __getitem__(self, index: int) -> Sample:
        """Return an index within the dataset.

        Args:
            index: index to return

        Returns:
            data and labels at that index

        Raises:
            IndexError: if index is out of range of the dataset
        """
        sample_df = self.df[self.df['num_index'] == index].copy()

        if self.as_time_series:
            image = self._load_time_series(sample_df)
        else:
            images = []
            for sensor in self.sensors:
                filenames = sample_df[sample_df['satellite'] == sensor][
                    'filename'
                ].tolist()
                images.append(self._load_input(filenames))
            image = torch.cat(images, dim=0)

        sample: Sample = {'image': image}
        if self.split == 'train':
            sample['mask'] = self._load_target(
                sample_df['corresponding_agbm'].unique()[0]
            ).squeeze(dim=0)

        return sample

    def _load_time_series(self, sample_df: pd.DataFrame) -> Tensor:
        """Load and fuse sensor imagery into a time series.

        Args:
            sample_df: Metadata rows for a single chip.

        Returns:
            Image tensor with shape ``(T, C, H, W)``.

        Raises:
            ValueError: If a sensor has multiple acquisitions in the same month.
        """
        frames = []
        for month in sorted(sample_df['num_month'].unique()):
            month_df = sample_df[sample_df['num_month'] == month]
            sensor_images: dict[str, Tensor] = {}
            for sensor in self.sensors:
                filenames = month_df[month_df['satellite'] == sensor][
                    'filename'
                ].tolist()
                if filenames:
                    if len(filenames) != 1:
                        msg = f'Expected one {sensor} acquisition per month.'
                        raise ValueError(msg)
                    sensor_images[sensor] = self._load_input(filenames)[0]

            reference = next(iter(sensor_images.values()))
            _, height, width = reference.shape
            channels = []
            for sensor in self.sensors:
                channels.append(
                    sensor_images.get(
                        sensor,
                        torch.zeros(
                            self.channel_counts[sensor],
                            height,
                            width,
                            dtype=reference.dtype,
                        ),
                    )
                )
            frames.append(torch.cat(channels, dim=0))

        return torch.stack(frames)

    def __len__(self) -> int:
        """Return the length of the dataset.

        Returns:
            length of the dataset
        """
        return len(self.df['num_index'].unique())

    def _load_input(self, filenames: list[Path]) -> Tensor:
        """Load the input imagery at the index.

        Args:
            filenames: list of filenames corresponding to input

        Returns:
            input image
        """
        filepaths = [
            os.path.join(self.root, f'{self.split}_features', f) for f in filenames
        ]
        arr_list = []
        for fp in filepaths:
            with rasterio.open(fp) as src:
                arr_list.append(src.read())
        if self.as_time_series:
            arr = np.stack(arr_list, axis=0)
        else:
            arr = np.concatenate(arr_list, axis=0)
        return torch.tensor(arr.astype(np.int32))

    def _load_target(self, filename: Path) -> Tensor:
        """Load the target mask at the index.

        Args:
            filename: filename of target to index

        Returns:
            target mask
        """
        with rasterio.open(os.path.join(self.root, 'train_agbm', filename), 'r') as src:
            arr: np.typing.NDArray[np.float64] = src.read()

        target = torch.from_numpy(arr).float()
        return target

    def _verify(self) -> None:
        """Verify the integrity of the dataset."""
        # Check if the extracted files already exist
        exists = []

        filenames = [f'{self.split}_features', self.metadata_filename]
        for filename in filenames:
            pathname = os.path.join(self.root, filename)
            exists.append(os.path.exists(pathname))
        if all(exists):
            return

        raise DatasetNotFoundError(self)

    def plot(
        self, sample: Sample, show_titles: bool = True, suptitle: str | None = None
    ) -> Figure:
        """Plot a sample from the dataset.

        Args:
            sample: a sample return by :meth:`__getitem__`
            show_titles: flag indicating whether to show titles above each panel
            suptitle: optional suptitle to use for figure

        Returns:
            a matplotlib Figure with the rendered sample
        """
        ncols = len(self.sensors)
        showing_predictions = 'prediction' in sample
        if showing_predictions:
            ncols += 1
        if 'mask' in sample:
            ncols += 1

        fig, axs_array = plt.subplots(
            1, ncols=ncols, figsize=(5 * ncols, 10), squeeze=False
        )
        axs = axs_array[0]
        image = sample['image'].float()
        expected_ndim = 4 if self.as_time_series else 3
        if image.ndim != expected_ndim:
            msg = f'Expected image tensor with {expected_ndim} dimensions.'
            raise ValueError(msg)
        if self.as_time_series:
            image = image[-1]

        channel_start = 0
        for idx, sens in enumerate(self.sensors):
            channel_end = channel_start + self.channel_counts[sens]
            img = image[channel_start:channel_end]
            channel_start = channel_end
            if sens == 'S2':
                img = img[[2, 1, 0], ...]
                img = quantile_normalization(einops.rearrange(img, 'c h w -> h w c'))
            else:
                co_polarization = img[0]  # transmit == receive
                cross_polarization = img[1]  # transmit != receive
                ratio = co_polarization / cross_polarization

                # https://gis.stackexchange.com/a/400780/123758
                co_polarization = torch.clamp(co_polarization / 0.3, 0, 1)
                cross_polarization = torch.clamp(cross_polarization / 0.05, 0, 1)
                ratio = torch.clamp(ratio / 25, 0, 1)

                img = torch.stack((co_polarization, cross_polarization, ratio), dim=-1)

            axs[idx].imshow(img)
            axs[idx].axis('off')
            if show_titles:
                axs[idx].set_title(sens)

        if showing_predictions:
            prediction = sample['prediction']
            if prediction.ndim == 3:
                prediction = prediction.squeeze(dim=0)
            prediction_idx = len(self.sensors)
            pred = axs[prediction_idx].imshow(prediction, cmap='YlGn')
            plt.colorbar(pred, ax=axs[prediction_idx], fraction=0.046, pad=0.04)
            axs[prediction_idx].axis('off')
            if show_titles:
                axs[prediction_idx].set_title('Prediction')

        if 'mask' in sample:
            target = axs[-1].imshow(sample['mask'], cmap='YlGn')
            plt.colorbar(target, ax=axs[-1], fraction=0.046, pad=0.04)
            axs[-1].axis('Off')
            if show_titles:
                axs[-1].set_title('Target')

        if suptitle is not None:
            plt.suptitle(suptitle)

        return fig
