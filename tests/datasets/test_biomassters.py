import hashlib
import os
import shutil
from itertools import product
from pathlib import Path

import matplotlib.pyplot as plt
import pytest
from _pytest.fixtures import SubRequest

from torchgeo.datasets import BioMassters, DatasetNotFoundError
from torchgeo.datasets.utils import check_integrity

DIRECTORY = os.path.join('tests', 'data', 'biomassters')


def _fixture_checksums() -> dict[str, str]:
    """Compute the real SHA-256 checksums of the small fixture archives.

    The fixtures generated by ``tests/data/biomassters/data.py`` are tiny
    stand-ins for the real (huge) upstream BioMassters archives, so they do not
    share the real checksums baked into :attr:`BioMassters.checksums`. Tests
    that exercise the real download/checksum code path monkeypatch
    ``BioMassters.checksums`` with the values returned here instead.
    """
    filenames = [
        *BioMassters.feature_archive_filenames['train'],
        *BioMassters.feature_archive_filenames['test'],
        BioMassters.target_archive_filenames['train'],
        BioMassters.metadata_filename,
    ]
    checksums = {}
    for filename in filenames:
        with open(os.path.join(DIRECTORY, filename), 'rb') as f:
            checksums[filename] = hashlib.sha256(f.read()).hexdigest()
    return checksums


def _fake_download_url(
    url: str, root: Path, filename: str | None = None, **kwargs: str | None
) -> None:
    """Stand-in for the network transfer performed by ``download_url``.

    Copies the matching fixture archive from :data:`DIRECTORY` into ``root``
    instead of issuing an HTTP request. Deliberately performs no checksum
    verification of its own -- that is the real ``download_url``'s
    responsibility. Tests that need to observe or exercise checksum handling
    either capture the ``sha256`` keyword argument BioMassters forwards (see
    ``_spy_download_url``) or delegate to the real
    :func:`~torchgeo.datasets.utils.check_integrity` (see
    ``_verifying_download_url``) rather than duplicating that logic here.
    """
    if not filename:
        filename = os.path.basename(url)
    os.makedirs(root, exist_ok=True)
    shutil.copy(os.path.join(DIRECTORY, filename), os.path.join(root, filename))


def _verifying_download_url(
    url: str, root: Path, filename: str | None = None, **kwargs: str | None
) -> None:
    """Like :func:`_fake_download_url`, but also runs the real
    :func:`~torchgeo.datasets.utils.check_integrity` used internally by the
    production ``download_url``, so checksum mismatch/bypass tests exercise
    the actual verification mechanism rather than a reimplementation of it.
    """
    if filename is None:
        filename = os.path.basename(url)
    _fake_download_url(url, root, filename=filename)
    fpath = os.path.join(root, filename)
    if not check_integrity(fpath, **kwargs):
        raise RuntimeError(f"Downloaded file '{fpath}' is corrupted.")


class TestBioMassters:
    @pytest.fixture(
        params=product(['train', 'test'], [['S1'], ['S2'], ['S1', 'S2']], [True, False])
    )
    def dataset(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path, request: SubRequest
    ) -> BioMassters:
        # BioMassters.url stays the real, pinned Hugging Face URL. Only the
        # network boundary (download_url) is mocked, so _verify/_download/
        # _extract and dataset loading all run for real against the local
        # fixture archives.
        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _fake_download_url
        )
        monkeypatch.setattr(BioMassters, 'checksums', _fixture_checksums())

        split, sensors, as_time_series = request.param
        return BioMassters(
            tmp_path,
            split=split,
            sensors=sensors,
            as_time_series=as_time_series,
            download=True,
        )

    def test_len_of_ds(self, dataset: BioMassters) -> None:
        assert len(dataset) > 0

    def test_not_downloaded(self, tmp_path: Path) -> None:
        with pytest.raises(DatasetNotFoundError, match='Dataset not found'):
            BioMassters(tmp_path)

    def test_download_test_split(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _fake_download_url
        )
        monkeypatch.setattr(BioMassters, 'checksums', _fixture_checksums())

        ds = BioMassters(tmp_path, split='test', download=True)

        assert os.path.isdir(os.path.join(tmp_path, 'test_features'))
        assert os.path.isfile(os.path.join(tmp_path, BioMassters.metadata_filename))
        assert len(ds) > 0
        ds[0]

    def test_download_train_split(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        # Exercises the real _download/_extract flow end to end, including
        # concatenating the split feature archives and extracting the train
        # target archive, without mocking either method.
        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _fake_download_url
        )
        monkeypatch.setattr(BioMassters, 'checksums', _fixture_checksums())

        ds = BioMassters(tmp_path, split='train', download=True)

        assert os.path.isdir(os.path.join(tmp_path, 'train_features'))
        assert os.path.isdir(os.path.join(tmp_path, 'train_agbm'))
        assert len(ds) > 0
        sample = ds[0]
        assert 'label' in sample

    def test_already_downloaded(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _fake_download_url
        )
        monkeypatch.setattr(BioMassters, 'checksums', _fixture_checksums())

        BioMassters(tmp_path, split='train', download=True)

        # If a second instantiation attempted to download again, this would
        # fail immediately.
        def _fail_download(*args: object, **kwargs: object) -> None:
            raise AssertionError('download_url should not be called again')

        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _fail_download
        )

        ds = BioMassters(tmp_path, split='train')
        assert len(ds) > 0

    def test_verify_repairs_missing_train_agbm(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        # Regression test: previously, _verify() considered the train split
        # "already extracted" as soon as train_features/ and the metadata csv
        # existed, even if train_agbm/ was missing or incomplete.
        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _fake_download_url
        )
        monkeypatch.setattr(BioMassters, 'checksums', _fixture_checksums())

        BioMassters(tmp_path, split='train', download=True)
        assert os.path.isdir(os.path.join(tmp_path, 'train_agbm'))

        shutil.rmtree(os.path.join(tmp_path, 'train_agbm'))

        # The downloaded archives (including train_agbm.tar.gz) are still on
        # disk, so re-instantiating without download=True should re-extract
        # train_agbm/ rather than raising or silently proceeding without it.
        def _fail_download(*args: object, **kwargs: object) -> None:
            raise AssertionError('download_url should not be called')

        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _fail_download
        )

        ds = BioMassters(tmp_path, split='train')
        assert os.path.isdir(os.path.join(tmp_path, 'train_agbm'))
        assert len(ds) > 0
        assert 'label' in ds[0]

    def test_download_forwards_expected_checksums(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        # Verifies that _download() forwards the correct sha256 value for
        # every archive it requests, rather than merely asserting a checksum
        # was passed. The spy performs no verification of its own.
        checksums = _fixture_checksums()
        monkeypatch.setattr(BioMassters, 'checksums', checksums)

        calls: list[tuple[str | None, str | None]] = []

        def _spy_download_url(
            url: str, root: Path, filename: str | None = None, **kwargs: str | None
        ) -> None:
            calls.append((filename, kwargs.get('sha256')))
            _fake_download_url(url, root, filename=filename)

        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _spy_download_url
        )

        BioMassters(tmp_path, split='test', download=True, checksum=True)

        expected_filenames = {
            *BioMassters.feature_archive_filenames['test'],
            BioMassters.metadata_filename,
        }
        assert {filename for filename, _ in calls} == expected_filenames
        for filename, sha256 in calls:
            assert filename is not None
            assert sha256 == checksums[filename]

    def test_download_checksum_false_forwards_none(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        # With checksum=False, _download() must forward sha256=None for every
        # archive regardless of what BioMassters.checksums contains.
        bad_checksum = '0' * 64
        bad_checksums = dict.fromkeys(
            [
                *BioMassters.feature_archive_filenames['test'],
                BioMassters.metadata_filename,
            ],
            bad_checksum,
        )
        monkeypatch.setattr(BioMassters, 'checksums', bad_checksums)

        calls: list[tuple[str | None, str | None]] = []

        def _spy_download_url(
            url: str, root: Path, filename: str | None = None, **kwargs: str | None
        ) -> None:
            calls.append((filename, kwargs.get('sha256')))
            _fake_download_url(url, root, filename=filename)

        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _spy_download_url
        )

        ds = BioMassters(tmp_path, split='test', download=True, checksum=False)

        assert calls
        for _, sha256 in calls:
            assert sha256 is None
        assert len(ds) > 0

    def test_download_checksum_mismatch(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        # Uses the real check_integrity mechanism (via _verifying_download_url)
        # to confirm a genuine checksum mismatch is actually detected.
        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _verifying_download_url
        )
        bad_checksum = '0' * 64
        bad_checksums = dict.fromkeys(
            [
                *BioMassters.feature_archive_filenames['test'],
                BioMassters.metadata_filename,
            ],
            bad_checksum,
        )
        monkeypatch.setattr(BioMassters, 'checksums', bad_checksums)

        with pytest.raises(RuntimeError, match='corrupted'):
            BioMassters(tmp_path, split='test', download=True, checksum=True)

    def test_download_without_checksum(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        # checksum=False must succeed via the real check_integrity mechanism
        # even when BioMassters.checksums is deliberately wrong.
        monkeypatch.setattr(
            'torchgeo.datasets.biomassters.download_url', _verifying_download_url
        )
        bad_checksum = '0' * 64
        bad_checksums = dict.fromkeys(
            [
                *BioMassters.feature_archive_filenames['test'],
                BioMassters.metadata_filename,
            ],
            bad_checksum,
        )
        monkeypatch.setattr(BioMassters, 'checksums', bad_checksums)

        ds = BioMassters(tmp_path, split='test', download=True, checksum=False)
        assert len(ds) > 0

    def test_plot(self, dataset: BioMassters) -> None:
        dataset.plot(dataset[0], suptitle='Test')
        plt.close()

        sample = dataset[0]
        if dataset.split == 'train':
            sample['prediction'] = sample['label']
        dataset.plot(sample)
        plt.close()
